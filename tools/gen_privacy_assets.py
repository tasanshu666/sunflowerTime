#!/usr/bin/env python3
"""从隐私政策底稿派生**应用内查看页**用的 Markdown 资产（单一事实源，勿手改）。

用法：
    /Users/wangjunchao/.workbuddy/binaries/python/envs/default/bin/python tools/gen_privacy_assets.py

输入（底稿）：
    docs/隐私政策_向日葵专注_v1.md        （固定底稿名，版本以头部三要素为准）
    docs/隐私政策_向日葵专注_v1_EN.md

输出（打包资产，pubspec `assets/docs/`）：
    assets/docs/privacy_policy_zh.md
    assets/docs/privacy_policy_en.md

与公网发布稿（tools/render_privacy.py）同源的加工规则（C110-7，2026-10-23 玄参反馈整改）：
  1. 自「附录 A / Appendix A」起整节剔除（中国大陆专项条款 + 附：待确认项汇总，
     均为内部/未来适用信息；公网发布稿仍保留全量）；
  2. 头部维护元信息引用行剔除（更新记录/维护人/包名/中国大陆引用等）；
  3. 正文内部话术剔除（审核提交话术/待上架前补全/同步维护草稿）；
  4. 占位符替换为中性表述。
应用内渲染由 lib/presentation/shared/privacy_policy_page.dart 的轻量
Markdown 渲染器完成（标题/引用/列表/表格行均支持）。
底稿改口径后重跑本脚本 + `flutter gen-l10n` 之外无需其它步骤。
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = ROOT / "assets" / "docs"

ZH_SRC = DOCS / "隐私政策_向日葵专注_v1.md"
EN_SRC = DOCS / "隐私政策_向日葵专注_v1_EN.md"

# 与 render_privacy.py 保持同源
ZH_REPLACEMENTS = [
    ("【开发者实体名称占位】", "向日葵专注 SunFocus（个人开发者）"),
    ("- 开发者实体名称 / 地址：【占位，上架前补全】", "- 开发者：向日葵专注 SunFocus（个人开发者）"),
    ("【待定】", "说明："),
    ("（待填）", ""),
]
EN_REPLACEMENTS = [
    ("【Developer legal entity name — placeholder】", "SunFocus (individual developer)"),
    ("- Developer legal entity name / address: 【placeholder — to be completed before launch】",
     "- Developer: SunFocus (individual developer)"),
    ("【TBD】", "Note:"),
    ("(TBD)", ""),
]

# 内部行（应用内不展示）：
#   · 维护元信息行（公网发布/发布稿生成/固定底稿名/更新记录/维护人/包名）
#   · 中国大陆专项条款引用行（附录 A 随 drop_heading 整节剔除，本行是其在头部的引用）
#   · EN 的英文版声明行（指向内部底稿路径）
INTERNAL_LINE = re.compile(
    r"^>.*(发布稿生成|公网发布|Generated by|Published at|固定底稿名|文件名中的|"
    r"更新记录|中国大陆专项条款|维护人|包名|"
    r"Change log|Mainland China addendum|Maintainer|fixed master-copy|Bundle ID|"
    r"English version of the SunFocus).*$\n?",
    re.MULTILINE,
)

# 正文内部话术（面向审核者/维护者，应用内不展示）
INTERNAL_PROSE_ZH = [
    ("，审核提交时填入各商店「隐私政策」字段", ""),
    ("；**数据控制者实体名称与联系地址待上架前补全**（见第九节）", ""),
    ("两版为同步维护的草稿；重大变更将在应用内或更新说明中提示。",
     "重大变更将在应用内或更新说明中提示。"),
]
INTERNAL_PROSE_EN = [
    (" and will be entered in the \"Privacy Policy\" field of each store at review submission", ""),
    ("; **the controller's legal entity name and contact address are to be completed before launch** (see Section 9)", ""),
    ("Both texts are synchronised drafts; material changes will be announced in the app or in the release notes.",
     "Material changes will be announced in the app or in the release notes."),
]


def render(src: pathlib.Path, drop_heading: str, replacements) -> str:
    text = src.read_text(encoding="utf-8")

    idx = text.find(drop_heading)
    if idx == -1:
        raise SystemExit(f"未找到待剔除小节：{drop_heading}（{src.name}）")
    text = text[:idx].rstrip().rstrip("-").rstrip()

    for old, new in replacements:
        text = text.replace(old, new)

    for old, new in INTERNAL_PROSE_ZH if src is ZH_SRC else INTERNAL_PROSE_EN:
        if old not in text:
            raise SystemExit(f"内部话术未命中（底稿可能已改，需同步规则）：{old[:30]}…（{src.name}）")
        text = text.replace(old, new)

    text = INTERNAL_LINE.sub("", text)

    # 节标题去「占位」字样（与 render_privacy.py 同源）
    text = text.replace("二、我们是谁（开发者信息占位）", "二、我们是谁（开发者信息）")
    text = text.replace("2. Who We Are (developer information placeholder)",
                        "2. Who We Are (developer information)")

    # 收敛连续空行（>3 → 2）
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    # drop_heading = 附录 A：自附录 A 起的内容（附录 A 中国大陆专项条款 + 附：待确认项汇总）
    # 均为内部/未来适用信息，应用内不展示（C110-7）。公网发布稿仍保留全量。
    zh = render(ZH_SRC, "## 附录 A：中国大陆专项条款", ZH_REPLACEMENTS)
    (OUT / "privacy_policy_zh.md").write_text(zh, encoding="utf-8")

    en = render(EN_SRC, "## Appendix A: Mainland China Addendum", EN_REPLACEMENTS)
    (OUT / "privacy_policy_en.md").write_text(en, encoding="utf-8")

    for name in ("privacy_policy_zh.md", "privacy_policy_en.md"):
        p = OUT / name
        print(f"{p}  ({p.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
