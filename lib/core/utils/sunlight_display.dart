/// 阳光数值的**展示口径**（全端唯一真源）。
///
/// ## 为什么需要这个函数（F105，2026-10-09 玄参发现）
/// 账本净额天然带小数——专注按分钟计酬（真机库实测 `sum(net) = 389.913261`），
/// 而孩子界面只展示整数。历史实现各页**各自取整且方向不一致**：
///   · 今日 / 花园 / 我的 → `.toInt()`（向下截断）→ 389；
///   · 商店（StoreBalancePill）→ `.round()`（四舍五入）→ **390**。
/// 结果同一时刻同一个余额在两个 tab 显示两个数（390 / 389），孩子会以为钱对不上。
///
/// ## 口径
/// 一律**向下取整**：孩子看到的可用阳光永不虚高。`.toInt()` 对正数等价 floor，
/// 与既有三处口径一致（改动面最小、不改变已验收页面的显示）。
/// 非正数（账本异常 / 待核销扣减超过余额）钳到 0，绝不展示负余额。
library sunlight_display;

/// 把账本余额（可能带小数）转成孩子界面展示用的整数。
///
/// 注意：本函数**只做展示取整**，不参与任何记账 / 比较 / 扣费。
/// 金额比较一律用原始 `double`（§3.2 账本铁律），避免取整方向影响判定。
int sunlightDisplayInt(double value) => value <= 0 ? 0 : value.toInt();
